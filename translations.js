const isSupportedLanguage = (language) => Object.prototype.hasOwnProperty.call(translations, language);

function setLanguage(language, remember = false) {
  const selected = isSupportedLanguage(language) ? language : "es";
  const copy = translations[selected];
  document.documentElement.lang = selected;
  document.title = copy.title;
  document.querySelector('meta[name="description"]').content = copy.meta;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = copy[element.dataset.i18n];
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    element.setAttribute("aria-label", copy[element.dataset.i18nAria]);
  });
  document.querySelectorAll("[data-language]").forEach((button) => {
    const active = button.dataset.language === selected;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });
  if (remember) {
    try { localStorage.setItem("peixescan-language", selected); } catch (_) { /* El selector sigue funcionando sin almacenamiento. */ }
  }
  window.dispatchEvent(new Event("peixescan-language-change"));
}

let savedLanguage;
try { savedLanguage = localStorage.getItem("peixescan-language"); } catch (_) { /* Se usa el idioma del navegador. */ }
const browserLanguage = (navigator.language || "es").split("-")[0].toLowerCase();
setLanguage(isSupportedLanguage(savedLanguage) ? savedLanguage : (isSupportedLanguage(browserLanguage) ? browserLanguage : "es"));

document.querySelectorAll("[data-language]").forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language, true));
});
